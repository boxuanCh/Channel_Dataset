def register_wireless_models(registry: ModelRegistry) -> None:
    """Register every configuration-backed wireless channel model.

    Parameters
    ----------
    registry : ModelRegistry
        Registry to populate. It must not already contain any of the wireless
        model keys.

    Notes
    -----
    Use the family-specific registration functions instead when an application
    intentionally exposes only a subset of the available models. AWGN is an
    independently applied noise component and is therefore not registered as a
    channel model.
    """

    _register_rayleigh_model(registry)
    _register_flat_mimo_model(registry)
    _register_tr38901_tdl_model(registry)
    _register_tr38901_cdl_model(registry)
    register_geometric_cdl_model(registry)
    register_ieee80211_models(registry)
    register_tr38811_models(registry)
    register_tr37885_models(registry)

